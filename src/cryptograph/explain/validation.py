"""Explanation Validation: Fidelity+, Fidelity-, Characterization scores, and Rank Correlation."""

from typing import Dict, List, Any
import numpy as np
import pandas as pd
from scipy.stats import spearmanr
import torch
import torch.nn as nn

class ExplanationValidator:
    """
    Validates explanations generated by graph explainers using:
    1. Fidelity+: Drop in prediction accuracy when important temporal motifs are removed.
    2. Characterization scores: Sparsity and Stability of the motif.
    3. Rank Correlation: Spearman rank correlation against statistical connectedness (Diebold-Yilmaz / VAR / PageRank).
    """

    def __init__(self, model: nn.Module):
        self.model = model

    def compute_fidelity_plus(
        self,
        node_features: torch.Tensor,
        edge_index: torch.Tensor,
        edge_mask: np.ndarray,
        target_idx: int,
        top_k_pct: float = 0.20
    ) -> float:
        r"""
        Computes Fidelity+ (Fidelity Drop):
        Fidelity+ = || f(G)[target] - f(G \ M)[target] ||_2
        Where M consists of the top-k% most important edges identified by the explainer.
        """
        self.model.eval()
        with torch.no_grad():
            out_orig = self.model(node_features, edge_index)
            y_orig = out_orig[0][target_idx] if isinstance(out_orig, tuple) else out_orig[target_idx]

            # Mask out the top-k% most important edges
            cutoff = np.percentile(edge_mask, (1.0 - top_k_pct) * 100.0)
            keep_indices = np.where(edge_mask < cutoff)[0]

            if len(keep_indices) == 0:
                return 0.0

            pruned_edge_index = edge_index[:, keep_indices]
            out_pruned = self.model(node_features, pruned_edge_index)
            y_pruned = out_pruned[0][target_idx] if isinstance(out_pruned, tuple) else out_pruned[target_idx]

            fidelity_plus = float(torch.norm(y_orig - y_pruned, p=2).item())

        return fidelity_plus

    def compute_fidelity_minus(
        self,
        node_features: torch.Tensor,
        edge_index: torch.Tensor,
        edge_mask: np.ndarray,
        target_idx: int,
        top_k_pct: float = 0.20
    ) -> float:
        r"""
        Computes Fidelity- (Prediction Retention under ablated background):
        Fidelity- = || f(G)[target] - f(M)[target] ||_2
        Where M consists ONLY of the top-k% most important explanatory edges.
        """
        self.model.eval()
        with torch.no_grad():
            out_orig = self.model(node_features, edge_index)
            y_orig = out_orig[0][target_idx] if isinstance(out_orig, tuple) else out_orig[target_idx]

            cutoff = np.percentile(edge_mask, (1.0 - top_k_pct) * 100.0)
            motif_indices = np.where(edge_mask >= cutoff)[0]

            if len(motif_indices) == 0:
                motif_edge_index = torch.empty((2, 0), dtype=torch.long, device=edge_index.device)
            else:
                motif_edge_index = edge_index[:, motif_indices]

            out_motif = self.model(node_features, motif_edge_index)
            y_motif = out_motif[0][target_idx] if isinstance(out_motif, tuple) else out_motif[target_idx]

            fidelity_minus = float(torch.norm(y_orig - y_motif, p=2).item())

        return fidelity_minus

    def compute_characterization_scores(self, edge_mask: np.ndarray) -> Dict[str, float]:
        """
        Calculates explanation characterization metrics:
        - Sparsity: Percentage of edges pruned.
        - Entropy: Concentration of attention mass.
        """
        sparsity = float(np.mean(edge_mask < 0.5))
        normalized = edge_mask / (np.sum(edge_mask) + 1e-8)
        entropy = float(-np.sum(normalized * np.log(normalized + 1e-8)))
        return {
            "sparsity": sparsity,
            "motif_entropy": entropy
        }

    def compute_rank_correlation(
        self,
        explainer_node_scores: Dict[str, float],
        reference_scores: pd.Series
    ) -> Dict[str, float]:
        """
        Computes Spearman rank correlation between explainer attribution ranking
        and econometric/network reference rankings (Diebold-Yilmaz Net Spillover or PageRank).
        """
        common_assets = [a for a in explainer_node_scores.keys() if a in reference_scores.index]
        if len(common_assets) < 3:
            return {"spearman_rho": 0.0, "p_value": 1.0}

        x_ranks = [explainer_node_scores[a] for a in common_assets]
        y_ranks = [reference_scores[a] for a in common_assets]

        rho, p_val = spearmanr(x_ranks, y_ranks)
        return {
            "spearman_rho": float(rho) if not np.isnan(rho) else 0.0,
            "p_value": float(p_val) if not np.isnan(p_val) else 1.0
        }
