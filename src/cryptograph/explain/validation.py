"""Explanation Validation: Fidelity+, Characterization scores, and Rank Correlation vs Econometric Connectedness."""

from typing import Dict, List, Any
import numpy as np
import pandas as pd
from scipy.stats import spearmanr
import torch
import torch.nn as nn

class ExplanationValidator:
    """
    Validates explanations generated by TempME using:
    1. Fidelity+: Drop in prediction accuracy when important temporal motifs are removed.
    2. Characterization scores: Sparsity and Stability of the motif.
    3. Rank Correlation: Spearman rank correlation against statistical connectedness (Diebold-Yilmaz / VAR).
    """

    def __init__(self, model: nn.Module):
        self.model = model

    def compute_fidelity_plus(
        self,
        node_features: torch.Tensor,
        edge_index: torch.Tensor,
        edge_mask: np.ndarray,
        target_idx: int,
        top_k_pct: float = 0.20
    ) -> float:
        r"""
        Computes Fidelity+ (Fidelity Drop):
        Fidelity+ = || f(G)[target] - f(G \ M)[target] ||_2
        Where M consists of the top-k% most important edges identified by TempME.
        """
        self.model.eval()
        with torch.no_grad():
            orig_preds, _ = self.model(node_features, edge_index)
            y_orig = orig_preds[target_idx]

            # Mask out the top-k% most important edges
            cutoff = np.percentile(edge_mask, (1.0 - top_k_pct) * 100.0)
            keep_indices = np.where(edge_mask < cutoff)[0]

            if len(keep_indices) == 0:
                return 0.0

            pruned_edge_index = edge_index[:, keep_indices]
            pruned_preds, _ = self.model(node_features, pruned_edge_index)
            y_pruned = pruned_preds[target_idx]

            fidelity_plus = float(torch.norm(y_orig - y_pruned, p=2).item())

        return fidelity_plus

    def compute_characterization_scores(self, edge_mask: np.ndarray) -> Dict[str, float]:
        """
        Calculates explanation characterization metrics:
        - Sparsity: Percentage of edges pruned.
        - Entropy: Concentration of attention mass.
        """
        sparsity = float(np.mean(edge_mask < 0.5))
        normalized = edge_mask / (np.sum(edge_mask) + 1e-8)
        entropy = float(-np.sum(normalized * np.log(normalized + 1e-8)))
        return {
            "sparsity": sparsity,
            "motif_entropy": entropy
        }

    def compute_rank_correlation(
        self,
        tempme_node_scores: Dict[str, float],
        statistical_connectedness: pd.Series
    ) -> Dict[str, float]:
        """
        Computes Spearman rank correlation between TempME's attribution ranking
        and econometric connectedness (Diebold-Yilmaz Net Spillover or VAR Granger ranks).
        """
        common_assets = [a for a in tempme_node_scores.keys() if a in statistical_connectedness.index]
        if len(common_assets) < 3:
            return {"spearman_rho": 0.0, "p_value": 1.0}

        x_ranks = [tempme_node_scores[a] for a in common_assets]
        y_ranks = [statistical_connectedness[a] for a in common_assets]

        rho, p_val = spearmanr(x_ranks, y_ranks)
        return {
            "spearman_rho": float(rho) if not np.isnan(rho) else 0.0,
            "p_value": float(p_val) if not np.isnan(p_val) else 1.0
        }
